bin="/usr/local/bin/${APP_APPLICATION_ID:?Remote did not supply the application id}"

if [ -z "${S3DISK_BUCKET:-}" ]; then
  echo "install: S3DISK_BUCKET is required (e.g. s3://my-bucket/project)" >&2
  exit 1
fi
case "$S3DISK_BUCKET" in
  s3://*) ;;
  *://*)
    echo "install: bucket must be s3://bucket[/prefix]; put a storage URL in Endpoint URL" >&2
    exit 1
    ;;
esac
if [ -z "${AWS_ACCESS_KEY_ID:-}" ] || [ -z "${AWS_SECRET_ACCESS_KEY:-}" ]; then
  echo "install: AWS_ACCESS_KEY_ID and AWS_SECRET_ACCESS_KEY are required" >&2
  exit 1
fi
case "$mountpoint" in
  /*) ;;
  *) echo "install: mountpoint must be an absolute path" >&2; exit 1 ;;
esac
case "$mountpoint" in
  /|/etc|/usr|/var|/root|/home|/workspace)
    echo "install: refusing to mount over ${mountpoint}" >&2
    exit 1
    ;;
esac

